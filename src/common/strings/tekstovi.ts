/** Умеће вредности у текст са местодржачима: `{путања}`. */
export const popuni = (tekst: string, vrednosti: Record<string, string | number>): string =>
  tekst.replace(/\{(\w+)\}/gu, (celo, kljuc) => String(vrednosti[kljuc] ?? celo))
